-- FRUIT TABLE
-- Stores the basic information for each fruit supported by the classification system.
-- The model_label links the fruit record with the class label produced by the ML model.
CREATE TABLE IF NOT EXISTS FRUIT (
    fruit_id INTEGER PRIMARY KEY,
    fruit_name TEXT NOT NULL UNIQUE,
    model_label TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL
);


-- SOURCE TABLE
-- Stores the sources used for nutrition, health benefit, and fun fact information.
-- Each source URL is unique to avoid storing the same source more than once.
CREATE TABLE IF NOT EXISTS SOURCE (
    source_id INTEGER PRIMARY KEY,
    source_name TEXT NOT NULL,
    source_url TEXT NOT NULL UNIQUE,
    access_date TEXT NOT NULL
);


-- NUTRITION TABLE
-- Stores nutritional information for each fruit.
-- Each fruit has one nutrition record and each record is linked to its information source.
CREATE TABLE IF NOT EXISTS NUTRITION (
    nutrition_id INTEGER PRIMARY KEY,
    fruit_id INTEGER NOT NULL UNIQUE,
    source_id INTEGER NOT NULL,
    serving_basis TEXT NOT NULL,
    energy_kcal REAL NOT NULL,
    protein_g REAL NOT NULL,
    carbohydrate_g REAL NOT NULL,
    sugars_g REAL NOT NULL,
    fibre_g REAL NOT NULL,
    fat_g REAL NOT NULL,
    potassium_mg REAL NOT NULL,
    vitamin_c_mg REAL NOT NULL,
    FOREIGN KEY (fruit_id) REFERENCES FRUIT(fruit_id),
    FOREIGN KEY (source_id) REFERENCES SOURCE(source_id)
);


-- USE TABLE
-- Stores the different common uses for each fruit.
-- One fruit can have multiple use records.
CREATE TABLE IF NOT EXISTS USE (
    use_id INTEGER PRIMARY KEY,
    fruit_id INTEGER NOT NULL,
    use_description TEXT NOT NULL,
    FOREIGN KEY (fruit_id) REFERENCES FRUIT(fruit_id)
);


-- HEALTH BENEFIT TABLE
-- Stores health benefit information associated with each fruit.
-- Each health benefit is linked to the fruit and the source supporting the information.
CREATE TABLE IF NOT EXISTS HEALTH_BENEFIT (
    benefit_id INTEGER PRIMARY KEY,
    fruit_id INTEGER NOT NULL,
    source_id INTEGER NOT NULL,
    benefit_description TEXT NOT NULL,
    FOREIGN KEY (fruit_id) REFERENCES FRUIT(fruit_id),
    FOREIGN KEY (source_id) REFERENCES SOURCE(source_id)
);


-- FUN FACT TABLE
-- Stores fun facts about each fruit.
-- Each fact is linked to a fruit and the source from which the information was obtained.
CREATE TABLE IF NOT EXISTS FUN_FACT (
    fact_id INTEGER PRIMARY KEY,
    fruit_id INTEGER NOT NULL,
    source_id INTEGER NOT NULL,
    fact_text TEXT NOT NULL,
    FOREIGN KEY (fruit_id) REFERENCES FRUIT(fruit_id),
    FOREIGN KEY (source_id) REFERENCES SOURCE(source_id)
);


-- PREDICTION HISTORY TABLE
-- Stores prediction results generated by the fruit classification system.
-- fruit_id can be NULL when the image is rejected or cannot be linked to a supported fruit.
-- The table also records confidence, class probabilities, prediction status, and model version.
CREATE TABLE IF NOT EXISTS PREDICTION_HISTORY (
    prediction_id INTEGER PRIMARY KEY,
    fruit_id INTEGER NULL,
    predicted_class TEXT NULL,
    apple_probability REAL NULL,
    banana_probability REAL NULL,
    confidence REAL NULL,
    prediction_status TEXT NOT NULL,
    rejection_reason TEXT NULL,
    model_version TEXT NOT NULL,
    FOREIGN KEY (fruit_id) REFERENCES FRUIT(fruit_id)
);